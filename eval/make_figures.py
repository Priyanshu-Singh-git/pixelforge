def font(size):
    for f in ("C:/Windows/Fonts/segoeuib.ttf", "C:/Windows/Fonts/arialbd.ttf"):
        if Path(f).exists():
            return ImageFont.truetype(f, size)
    return ImageFont.load_default()


def label(img, text, size=26):
    im = Image.fromarray(img).convert("RGB")
    d = ImageDraw.Draw(im)
    f = font(size)
    w = d.textlength(text, font=f)
    d.rounded_rectangle([10, 10, 10 + w + 20, 10 + size + 16], 8, fill=(255, 255, 255))
    d.text((20, 16), text, font=f, fill=(31, 41, 55))
    return np.array(im)


def zoom_grid(d, picks, fns, crop=192, out_px=336):
    rows = []
    for k in picks:
        hr = d["hr"][k]
        y = x = (512 - crop * 1) // 2
        tiles = []
        for name, fn in fns:
            img = hr if fn is None else fn(d["lr"][k])
            c = cv2.resize(img[y:y + crop, x:x + crop], (out_px, out_px), interpolation=cv2.INTER_NEAREST)
            tiles.append(label(c, name, 22))
        rows.append(np.concatenate([np.pad(t, ((6, 6), (6, 6), (0, 0)), constant_values=255) for t in tiles], 1))
    return np.concatenate(rows, 0)


def hero_split(lr, sr, size=900):
    bic = cv2.resize(lr, (512, 512), interpolation=cv2.INTER_CUBIC)
    a = cv2.resize(bic, (size, size), interpolation=cv2.INTER_LANCZOS4)
    b = cv2.resize(sr, (size, size), interpolation=cv2.INTER_LANCZOS4)
    out = a.copy()
    out[:, size // 2:] = b[:, size // 2:]
    out[:, size // 2 - 3:size // 2 + 3] = 255
    out = label(out, "Before (bicubic)", 34)
    im = Image.fromarray(out)
    d = ImageDraw.Draw(im)
    f = font(34)
    t = "PixelForge 4×"
    w = d.textlength(t, font=f)
    d.rounded_rectangle([size - w - 40, 10, size - 10, 60], 8, fill=(234, 88, 12))
    d.text((size - w - 30, 16), t, font=f, fill=(255, 255, 255))
    return np.array(im)


def curves():
    fig, ax = plt.subplots(figsize=(7.5, 3.6))
    for name, color, lab in [("rrdb_s_psnr", ORANGE, "RRDB-S (L1)"), ("srvgg_s_psnr", SLATE, "SRVGG-S (L1)")]:
        p = ROOT / "train" / "runs" / f"{name}.jsonl"
        if p.exists():
            r = [json.loads(l) for l in p.read_text().splitlines()]
            ax.plot([x["it"] for x in r], [x["val_psnr"] for x in r], "-o", color=color, lw=2, ms=5, label=lab)
    ax.set_xlabel("training iteration"); ax.set_ylabel("validation PSNR (dB)")
    ax.set_title("Validation PSNR during training", loc="left", fontweight="bold")
    ax.grid(color=GRID); [ax.spines[s].set_visible(False) for s in ("top", "right")]
    ax.legend(frameon=False)
    fig.tight_layout(); fig.savefig(FIG / "training_curves.png", dpi=180); plt.close(fig)


def report(rows):
    md = ["# PixelForge: evaluation results", "",
          "Held-out **test** set: 60 Poly Haven CC0 textures never used for training or checkpoint selection "
          "(split by texture). Centre 512×512 crop → degraded → 128×128 input → ×4. Metrics on RGB, 4-px border "
          "cropped. Generated by `eval/evaluate.py` + `eval/make_figures.py`; nothing hand-entered.", ""]
    for cond, title in (("real", "Realistic degradation (blur + downscale + noise + JPEG)"),
                        ("bicubic", "Clean bicubic downscale (classic SR setting)")):
        md += [f"## {title}", "", "| Method | Params | PSNR ↑ | SSIM ↑ | LPIPS ↓ | GPU ms / 128² tile | CPU ms (4 thr) |",
               "|---|---|---|---|---|---|---|"]
        for r in [x for x in rows if x["condition"] == cond]:
            p = f"{r['params_m']:.2f}M" if r["params_m"] else "–"
            g = f"{r['gpu_ms']:.1f}" if r.get("gpu_ms") else "–"
            c = f"{r['cpu_ms_4threads']:.0f}" if r.get("cpu_ms_4threads") else "–"
            name = f"**{r['method']}**" if "(mine)" in r["method"] else r["method"]
            md.append(f"| {name} | {p} | {r['psnr']:.2f} | {r['ssim']:.4f} | {r['lpips']:.4f} | {g} | {c} |")
        md.append("")
    md += ["GPU: " + str(rows[-1].get("gpu")) + " (fp16). Timings are for one 128×128 → 512×512 texture.", "",
           "![Zoomed comparison](../assets/figures/zoom_comparison.png)", "",
           "![Training curves](../assets/figures/training_curves.png)", ""]
    (ROOT / "eval" / "results.md").write_text("\n".join(md), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--best", default="rrdb_s_gan")
    ap.add_argument("--hero", default="slumped_mortar_brick")
    args = ap.parse_args()
    FIG.mkdir(parents=True, exist_ok=True)
    rows = [json.loads(l) for l in (ROOT / "eval" / "results.jsonl").read_text().splitlines()]
    report(rows)
    curves()
    d = build_eval_set("test", "real")
    best = neural(load_ours(args.best))
    fns = [("Low-res input", classical(cv2.INTER_NEAREST)), ("Bicubic", classical(cv2.INTER_CUBIC)),
           ("Real-ESRGAN", neural(load_pretrained("RealESRGAN_x4plus"))), ("PixelForge", best), ("True HD", None)]
    # representative picks: the textures with median PixelForge-vs-bicubic LPIPS gain, from 3 categories
    key = {"rrdb_s_gan": "PixelForge_RRDB-S_GAN", "rrdb_s_psnr": "PixelForge_RRDB-S_L1",
           "srvgg_s_psnr": "PixelForge_SRVGG-S_L1"}[args.best]  # file names written by evaluate.py
    per = {r["slug"]: r for r in json.loads((ROOT / "eval" / "per_image" / f"{key}_real.json").read_text())}
    bic = {r["slug"]: r for r in json.loads((ROOT / "eval" / "per_image" / "Bicubic_real.json").read_text())}
    # gallery = representative: textures around the MEDIAN PixelForge-vs-bicubic LPIPS gain, skipping near-black
    # ones (mean brightness < 70, where no method shows visible detail), one per category
    lum = {k: d["hr"][k].mean() for k in range(len(d["slug"]))}
    gain = sorted((k for k in range(len(d["slug"])) if lum[k] >= 70),
                  key=lambda k: bic[str(d["slug"][k])]["lpips"] - per[str(d["slug"][k])]["lpips"])
    mid = len(gain) // 2
    window = sorted(gain, key=lambda k: abs(gain.index(k) - mid))[:10]
    cats = {m["slug"]: (m["categories"] or ["x"])[0] for m in load_manifest("test")}
    picks, seen = [], set()
    for k in window:
        c = cats[str(d["slug"][k])]
        if c not in seen:
            seen.add(c); picks.append(k)
    picks = picks[:3]
    Image.fromarray(zoom_grid(d, picks, fns)).save(FIG / "zoom_comparison.png")
    # cover hero = a strong (not typical) example, chosen explicitly and named in the README
    k = list(map(str, d["slug"])).index(args.hero)
    Image.fromarray(hero_split(d["lr"][k], best(d["lr"][k]))).save(FIG / "hero_split.png")
    print("figures:", sorted(p.name for p in FIG.glob("*.png")), "| picks:", [str(d["slug"][i]) for i in picks])


if __name__ == "__main__":
    main()
